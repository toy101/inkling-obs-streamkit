import { chmod, mkdir } from "node:fs/promises";
import { resolve } from "node:path";

import { parseHttpsOrigin } from "../env";

const CONFIG_NAME = "wrangler.production.toml";
const ENVIRONMENT = "production";
const LOCAL_DATABASE_ID = "00000000-0000-0000-0000-000000000001";
const GENERATED_MARKER = "# Generated by src/db/wrangler-production.ts\n";
const LEGACY_CLOUDFLARE_ENVIRONMENT_VARIABLES = [
  "CLOUDFLARE_API_TOKEN",
  "CLOUDFLARE_ACCOUNT_ID",
  "CLOUDFLARE_API_KEY",
  "CLOUDFLARE_EMAIL",
  "CF_API_TOKEN",
  "CF_ACCOUNT_ID",
  "CF_API_KEY",
  "CF_EMAIL",
] as const;
const APPLICATION_TABLES = new Set([
  "positions",
  "players",
  "player_weapons",
  "tournaments",
  "tournament_teams",
  "tournament_roster_entries",
  "tournament_roster_weapons",
  "seed_history",
  "rules",
  "stages",
  "weapons",
]);

type ProductionAction = "dev" | "check" | "migrate" | "seed";

type CommandResult = {
  exitCode: number;
  stdout: string;
  stderr: string;
};

export type WranglerRunner = (
  args: readonly string[],
  options: { capture: boolean; env: Record<string, string> },
) => Promise<CommandResult>;

type ProductionBinding = {
  binding: string;
  databaseName: string;
  databaseId: string;
  remote: true;
  migrationsDir: string;
  migrationsTable: string;
};

type ProductionConfig = {
  accountId: string;
  name: string;
  main: string;
  compatibilityDate: string;
  binding: ProductionBinding;
};

type DatabaseInventory = {
  tables: string[];
  legacyMigrations: string[] | null;
  wranglerMigrations: string[] | null;
};

export type ProductionRuntimeOptions = {
  apiRoot?: string;
  runner?: WranglerRunner;
  environment?: Record<string, string>;
  log?: (message: string) => void;
};

function record(value: unknown, name: string): Record<string, unknown> {
  if (typeof value !== "object" || value === null || Array.isArray(value)) {
    throw new Error(`${name} must be a TOML table.`);
  }
  return value as Record<string, unknown>;
}

function stringField(source: Record<string, unknown>, key: string, name: string): string {
  const value = source[key];
  if (typeof value !== "string" || value.trim() === "") {
    throw new Error(`${name}.${key} must be a non-empty string.`);
  }
  return value.trim();
}

function rejectPlaceholder(value: string, name: string): void {
  if (/placeholder|change[-_ ]?me|your[-_ <]|<[^>]+>|example/i.test(value)) {
    throw new Error(`${name} still contains an example or placeholder value.`);
  }
}

export function parseProductionConfig(source: string): ProductionConfig {
  let parsed: unknown;
  try {
    parsed = Bun.TOML.parse(source);
  } catch (error) {
    throw new Error(`Could not parse ${CONFIG_NAME}: ${String(error)}`);
  }

  const root = record(parsed, CONFIG_NAME);
  const accountId = stringField(root, "account_id", CONFIG_NAME);
  if (!/^[0-9a-f]{32}$/i.test(accountId)) {
    throw new Error(`${CONFIG_NAME}.account_id must be a 32-character hexadecimal account ID.`);
  }
  rejectPlaceholder(accountId, `${CONFIG_NAME}.account_id`);

  const name = stringField(root, "name", CONFIG_NAME);
  const main = stringField(root, "main", CONFIG_NAME);
  const compatibilityDate = stringField(root, "compatibility_date", CONFIG_NAME);
  rejectPlaceholder(name, `${CONFIG_NAME}.name`);
  if (main !== "src/worker.ts") {
    throw new Error(`${CONFIG_NAME}.main must be "src/worker.ts".`);
  }
  if (!/^\d{4}-\d{2}-\d{2}$/.test(compatibilityDate)) {
    throw new Error(`${CONFIG_NAME}.compatibility_date must use YYYY-MM-DD.`);
  }

  const env = record(root.env, `${CONFIG_NAME}.env`);
  const production = record(env.production, `${CONFIG_NAME}.env.production`);
  for (const [key, expected] of [
    ["account_id", accountId],
    ["main", main],
  ] as const) {
    const override = production[key];
    if (override !== undefined && override !== expected) {
      throw new Error(`${CONFIG_NAME}.env.production.${key} must match the top-level value.`);
    }
  }
  const databaseList = production.d1_databases;
  if (!Array.isArray(databaseList) || databaseList.length !== 1) {
    throw new Error(`${CONFIG_NAME}.env.production must contain exactly one D1 binding.`);
  }
  const database = record(databaseList[0], `${CONFIG_NAME}.env.production.d1_databases[0]`);
  const binding = stringField(database, "binding", "production D1 binding");
  const databaseName = stringField(database, "database_name", "production D1 binding");
  const databaseId = stringField(database, "database_id", "production D1 binding");
  const migrationsDir = stringField(database, "migrations_dir", "production D1 binding");
  const migrationsTable = stringField(database, "migrations_table", "production D1 binding");
  rejectPlaceholder(databaseName, "production D1 database_name");
  rejectPlaceholder(databaseId, "production D1 database_id");

  if (binding !== "DB") throw new Error("Production D1 binding must be named DB.");
  if (database.remote !== true) throw new Error("Production D1 binding must set remote = true.");
  if (!/^[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}$/i.test(databaseId)) {
    throw new Error("Production D1 database_id must be a valid UUID.");
  }
  if (databaseId === LOCAL_DATABASE_ID) {
    throw new Error("Production D1 database_id must not use the local dummy database ID.");
  }
  if (migrationsDir !== "src/db/migrations") {
    throw new Error("Production D1 migrations_dir must be src/db/migrations.");
  }
  if (migrationsTable !== "d1_migrations") {
    throw new Error("Production D1 migrations_table must be d1_migrations.");
  }

  return {
    accountId,
    name,
    main,
    compatibilityDate,
    binding: {
      binding,
      databaseName,
      databaseId,
      remote: true,
      migrationsDir,
      migrationsTable,
    },
  };
}

export const defaultWranglerRunner: WranglerRunner = async (args, options) => {
  const bun = Bun.which("bun");
  if (bun === null) throw new Error("Bun is required to run Wrangler.");
  const child = Bun.spawn({
    cmd: [bun, "run", "wrangler", ...args],
    cwd: resolve(import.meta.dir, "../.."),
    env: options.env,
    stdin: "inherit",
    stdout: options.capture ? "pipe" : "inherit",
    stderr: options.capture ? "pipe" : "inherit",
  });
  const [exitCode, stdout, stderr] = await Promise.all([
    child.exited,
    options.capture ? new Response(child.stdout).text() : Promise.resolve(""),
    options.capture ? new Response(child.stderr).text() : Promise.resolve(""),
  ]);
  return { exitCode, stdout, stderr };
};

async function runWrangler(
  runner: WranglerRunner,
  args: readonly string[],
  environment: Record<string, string>,
  capture: boolean,
): Promise<CommandResult> {
  const result = await runner(args, { capture, env: { ...environment } });
  if (result.exitCode !== 0) {
    const details = [result.stderr.trim(), result.stdout.trim()].filter(Boolean).join("\n");
    throw new Error(`Wrangler exited with code ${result.exitCode}.${details ? `\n${details}` : ""}`);
  }
  return result;
}

function parseDotEnv(source: string): Record<string, string> {
  const result: Record<string, string> = {};
  for (const rawLine of source.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (line === "" || line.startsWith("#")) continue;
    const separator = line.indexOf("=");
    if (separator < 1) continue;
    const key = line.slice(0, separator).trim().replace(/^export\s+/, "");
    let value = line.slice(separator + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    result[key] = value;
  }
  return result;
}

async function assertWranglerOAuthEnvironment(
  apiRoot: string,
  environment: Record<string, string>,
): Promise<void> {
  const envFile = Bun.file(resolve(apiRoot, ".env.local"));
  const fileValues = await envFile.exists() ? parseDotEnv(await envFile.text()) : {};
  const conflicts = LEGACY_CLOUDFLARE_ENVIRONMENT_VARIABLES.filter((name) =>
    (environment[name]?.trim() ?? "") !== "" || (fileValues[name]?.trim() ?? "") !== ""
  );
  if (conflicts.length > 0) {
    throw new Error(
      `Remove ${conflicts.join(", ")} from apps/api/.env.local and unset them in your shell. `
      + `Production Wrangler commands use "wrangler login" and ${CONFIG_NAME}.account_id.`,
    );
  }
}

async function readProductionVariables(apiRoot: string, environment: Record<string, string>): Promise<Record<string, string>> {
  const envFile = Bun.file(resolve(apiRoot, ".env.local"));
  const fileValues = await envFile.exists() ? parseDotEnv(await envFile.text()) : {};
  const get = (name: string): string => {
    const value = environment[name]?.trim() || fileValues[name]?.trim();
    if (!value) throw new Error(`${name} must be set in apps/api/.env.local.`);
    return value;
  };
  const catalogUrl = new URL(get("CATALOG_URL"));
  if (catalogUrl.protocol !== "https:") {
    throw new Error("CATALOG_URL must use HTTPS.");
  }
  return {
    CATALOG_URL: catalogUrl.href,
    IKACLO_API_ORIGIN: parseHttpsOrigin(get("IKACLO_API_ORIGIN"), "IKACLO_API_ORIGIN"),
    ADMIN_API_TOKEN: get("ADMIN_API_TOKEN"),
  };
}

export async function writeProductionVars(
  apiRoot: string,
  environment: Record<string, string>,
): Promise<string> {
  const path = resolve(apiRoot, `.dev.vars.${ENVIRONMENT}`);
  const existing = Bun.file(path);
  if (await existing.exists() && !(await existing.text()).startsWith(GENERATED_MARKER)) {
    throw new Error(`${path} exists and was not generated by this command.`);
  }
  const values = await readProductionVariables(apiRoot, environment);
  const source = GENERATED_MARKER + [
    `CATALOG_URL=${JSON.stringify(values.CATALOG_URL)}`,
    `CORS_ALLOWED_ORIGINS=${JSON.stringify("http://localhost:5173,http://127.0.0.1:5173")}`,
    `IKACLO_API_ORIGIN=${JSON.stringify(values.IKACLO_API_ORIGIN)}`,
    `ADMIN_ENVIRONMENT="production"`,
    `ADMIN_ALLOWED_ORIGINS=${JSON.stringify("http://localhost:5174,http://127.0.0.1:5174")}`,
    `ADMIN_API_TOKEN=${JSON.stringify(values.ADMIN_API_TOKEN)}`,
  ].join("\n") + "\n";
  await Bun.write(path, source);
  await chmod(path, 0o600);
  return path;
}

function parseD1Rows(stdout: string): Array<Record<string, unknown>> {
  let parsed: unknown;
  try {
    parsed = JSON.parse(stdout);
  } catch {
    throw new Error("Wrangler returned invalid JSON while inspecting production D1.");
  }
  const items = Array.isArray(parsed) ? parsed : [parsed];
  const rows: Array<Record<string, unknown>> = [];
  for (const item of items) {
    const result = record(item, "Wrangler D1 result");
    if (result.success === false) throw new Error("Wrangler reported an unsuccessful D1 query.");
    const resultRows = result.results;
    if (!Array.isArray(resultRows)) continue;
    for (const row of resultRows) rows.push(record(row, "Wrangler D1 row"));
  }
  return rows;
}

function baseDatabaseArgs(config: ProductionConfig): string[] {
  return [config.binding.databaseName, "--remote", "--config", CONFIG_NAME, "--env", ENVIRONMENT];
}

async function queryRows(
  runner: WranglerRunner,
  config: ProductionConfig,
  environment: Record<string, string>,
  sql: string,
): Promise<Array<Record<string, unknown>>> {
  const result = await runWrangler(runner, [
    "d1", "execute", ...baseDatabaseArgs(config), "--yes", "--json", "--command", sql,
  ], environment, true);
  return parseD1Rows(result.stdout);
}

function migrationNames(rows: Array<Record<string, unknown>>, table: string): string[] {
  return rows.map((row) => {
    if (typeof row.name !== "string") throw new Error(`${table} contains an invalid migration name.`);
    return row.name;
  });
}

async function inspectDatabase(
  runner: WranglerRunner,
  config: ProductionConfig,
  environment: Record<string, string>,
): Promise<DatabaseInventory> {
  const tableRows = await queryRows(
    runner,
    config,
    environment,
    "SELECT name FROM sqlite_master WHERE type = 'table' ORDER BY name",
  );
  const tables = tableRows.flatMap((row) => typeof row.name === "string" ? [row.name] : []);
  const legacyMigrations = tables.includes("schema_migrations")
    ? migrationNames(await queryRows(runner, config, environment, "SELECT name FROM schema_migrations ORDER BY name"), "schema_migrations")
    : null;
  const wranglerMigrations = tables.includes(config.binding.migrationsTable)
    ? migrationNames(await queryRows(runner, config, environment, `SELECT name FROM ${config.binding.migrationsTable} ORDER BY id`), config.binding.migrationsTable)
    : null;
  return { tables, legacyMigrations, wranglerMigrations };
}

async function repositoryMigrations(apiRoot: string): Promise<string[]> {
  const glob = new Bun.Glob("*.sql");
  const names: string[] = [];
  for await (const name of glob.scan({ cwd: resolve(apiRoot, "src/db/migrations"), onlyFiles: true })) {
    names.push(name);
  }
  return names.sort();
}

function validateHistory(history: readonly string[], repository: readonly string[], table: string): void {
  const known = new Set(repository);
  const unknown = history.filter((name) => !known.has(name));
  if (unknown.length > 0) {
    throw new Error(`${table} contains unknown migrations: ${unknown.join(", ")}`);
  }
  const expectedPrefix = repository.slice(0, history.length);
  if (history.some((name, index) => name !== expectedPrefix[index])) {
    throw new Error(`${table} is not a contiguous prefix of this repository's migrations.`);
  }
}

function applicationTables(tables: readonly string[]): string[] {
  return tables.filter((name) => APPLICATION_TABLES.has(name));
}

function sqlLiteral(value: string): string {
  return `'${value.replaceAll("'", "''")}'`;
}

async function prepareMigrationHistory(
  runner: WranglerRunner,
  config: ProductionConfig,
  environment: Record<string, string>,
  apiRoot: string,
  inventory: DatabaseInventory,
): Promise<void> {
  const repository = await repositoryMigrations(apiRoot);
  if (inventory.legacyMigrations !== null) validateHistory(inventory.legacyMigrations, repository, "schema_migrations");
  if (inventory.wranglerMigrations !== null) validateHistory(inventory.wranglerMigrations, repository, config.binding.migrationsTable);

  const tables = applicationTables(inventory.tables);
  const noAppliedHistory = (inventory.legacyMigrations?.length ?? 0) === 0
    && (inventory.wranglerMigrations?.length ?? 0) === 0;
  if (noAppliedHistory && tables.length > 0) {
    throw new Error(`Production D1 already has application tables but no applied migration history: ${tables.join(", ")}. Refusing to guess migration state.`);
  }
  if (inventory.legacyMigrations === null && inventory.wranglerMigrations === null) {
    return;
  }
  if (inventory.legacyMigrations === null) return;

  const wranglerApplied = new Set(inventory.wranglerMigrations ?? []);
  const missing = inventory.legacyMigrations.filter((name) => !wranglerApplied.has(name));
  if (missing.length === 0) return;
  const create = `CREATE TABLE IF NOT EXISTS ${config.binding.migrationsTable} (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT UNIQUE, applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL)`;
  const inserts = missing.map((name) => `INSERT INTO ${config.binding.migrationsTable} (name) VALUES (${sqlLiteral(name)})`);
  await runWrangler(runner, [
    "d1", "execute", ...baseDatabaseArgs(config), "--command", `${create};${inserts.join(";")};`,
  ], environment, false);
}

function describeTarget(config: ProductionConfig, log: (message: string) => void): void {
  log(`Cloudflare account: ${config.accountId}`);
  log(`Production D1: ${config.binding.databaseName} (${config.binding.databaseId})`);
  log(`Worker environment: ${ENVIRONMENT}; binding: ${config.binding.binding}; remote: true`);
}

function validateDatabaseInfo(stdout: string, config: ProductionConfig): void {
  let parsed: unknown;
  try {
    parsed = JSON.parse(stdout);
  } catch {
    throw new Error("Wrangler returned invalid JSON for production D1 info.");
  }
  const value = Array.isArray(parsed) ? parsed[0] : parsed;
  const info = record(value, "Wrangler D1 info");
  const id = typeof info.uuid === "string" ? info.uuid : info.id;
  if (id !== config.binding.databaseId) {
    throw new Error(`Wrangler D1 info returned an unexpected database ID: ${String(id)}.`);
  }
  if (info.name !== config.binding.databaseName) {
    throw new Error(`Wrangler D1 info returned an unexpected database name: ${String(info.name)}.`);
  }
}

async function loadConfig(apiRoot: string): Promise<ProductionConfig> {
  const file = Bun.file(resolve(apiRoot, CONFIG_NAME));
  if (!(await file.exists())) {
    throw new Error(`Missing apps/api/${CONFIG_NAME}. Copy wrangler.production.example.toml and replace every example value.`);
  }
  return parseProductionConfig(await file.text());
}

export async function runProductionAction(
  action: ProductionAction,
  options: ProductionRuntimeOptions = {},
): Promise<void> {
  const apiRoot = options.apiRoot ?? resolve(import.meta.dir, "../..");
  const runner = options.runner ?? defaultWranglerRunner;
  const environment = options.environment ?? Object.fromEntries(
    Object.entries(Bun.env).flatMap(([key, value]) => value === undefined ? [] : [[key, value]]),
  );
  const log = options.log ?? console.log;
  const config = await loadConfig(apiRoot);
  await assertWranglerOAuthEnvironment(apiRoot, environment);
  describeTarget(config, log);

  if (action === "dev") {
    await writeProductionVars(apiRoot, environment);
    await runWrangler(runner, [
      "dev", "--config", CONFIG_NAME, "--env", ENVIRONMENT, "--ip", "127.0.0.1", "--port", "3000",
    ], environment, false);
    return;
  }

  if (action === "check") {
    const info = await runWrangler(runner, [
      "d1", "info", config.binding.databaseName,
      "--config", CONFIG_NAME, "--env", ENVIRONMENT, "--json",
    ], environment, true);
    validateDatabaseInfo(info.stdout, config);
    const inventory = await inspectDatabase(runner, config, environment);
    const repository = await repositoryMigrations(apiRoot);
    if (inventory.legacyMigrations !== null) validateHistory(inventory.legacyMigrations, repository, "schema_migrations");
    if (inventory.wranglerMigrations !== null) validateHistory(inventory.wranglerMigrations, repository, config.binding.migrationsTable);
    const existingWithoutHistory = (inventory.legacyMigrations?.length ?? 0) === 0
      && (inventory.wranglerMigrations?.length ?? 0) === 0
      && applicationTables(inventory.tables).length > 0;
    log(`Tables: ${inventory.tables.length === 0 ? "(empty)" : inventory.tables.join(", ")}`);
    log(`Legacy migration history: ${inventory.legacyMigrations?.length ?? 0}`);
    log(`Wrangler migration history: ${inventory.wranglerMigrations?.length ?? 0}`);
    if (existingWithoutHistory) {
      log("Migration readiness: blocked; application tables exist without schema_migrations or d1_migrations.");
    } else if (inventory.legacyMigrations !== null && inventory.wranglerMigrations === null) {
      log("Migration readiness: legacy history will be copied to d1_migrations before migration; schema_migrations will be preserved.");
    } else {
      log("Migration readiness: ready.");
    }
    return;
  }

  if (action === "seed" && environment.D1_SEED_DEVELOPMENT_DATA !== "1") {
    throw new Error("Set D1_SEED_DEVELOPMENT_DATA=1 to seed the production D1 database.");
  }

  const inventory = await inspectDatabase(runner, config, environment);
  await prepareMigrationHistory(runner, config, environment, apiRoot, inventory);
  await runWrangler(runner, [
    "d1", "migrations", "apply", ...baseDatabaseArgs(config),
  ], environment, false);

  if (action === "seed") {
    const { createLocalSeedSql } = await import("./local-seed-sql");
    const dataDirectory = resolve(apiRoot, ".data");
    const seedPath = resolve(dataDirectory, "d1-production-seed.sql");
    await mkdir(dataDirectory, { recursive: true });
    await Bun.write(seedPath, createLocalSeedSql());
    await runWrangler(runner, [
      "d1", "execute", ...baseDatabaseArgs(config), "--file", seedPath,
    ], environment, false);
  }
}

if (import.meta.main) {
  const action = process.argv[2];
  if (action !== "dev" && action !== "check" && action !== "migrate" && action !== "seed") {
    throw new Error("Usage: bun run src/db/wrangler-production.ts <dev|check|migrate|seed>");
  }
  await runProductionAction(action);
}
