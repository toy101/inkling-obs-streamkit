import { chmod, mkdir } from "node:fs/promises";
import { resolve } from "node:path";

import { parseCatalogBaseUrl } from "../../../../scripts/prepare-runtime-assets";
import { parseHttpsOrigin, requireEnvironmentVariable } from "../env";
import { createLocalSeedSql } from "./local-seed-sql";

const apiRoot = resolve(import.meta.dir, "../..");
const stateDirectory = resolve(apiRoot, ".data/wrangler");
const seedPath = resolve(apiRoot, ".data/d1-seed.sql");
const varsPath = resolve(apiRoot, ".dev.vars");
const generatedMarker = "# Generated by src/db/setup-local.ts\n";

async function runWrangler(args: string[]): Promise<void> {
  const bun = Bun.which("bun");
  if (bun === null) throw new Error("Bun is required for local D1 setup.");
  const process = Bun.spawn({
    cmd: [bun, "run", "wrangler", ...args],
    cwd: apiRoot,
    env: { ...Bun.env, CI: "true" },
    stdin: "inherit",
    stdout: "inherit",
    stderr: "inherit",
  });
  const exitCode = await process.exited;
  if (exitCode !== 0) {
    throw new Error(`Wrangler exited with code ${exitCode}.`);
  }
}

async function writeLocalVars(): Promise<void> {
  const existing = Bun.file(varsPath);
  if (await existing.exists() && !(await existing.text()).startsWith(generatedMarker)) {
    throw new Error(`${varsPath} exists and was not generated by this command.`);
  }
  const catalogUrl = parseCatalogBaseUrl().href;
  if (!catalogUrl.startsWith("https://")) {
    throw new Error("Local API Worker requires an HTTPS CATALOG_URL.");
  }
  const imageOrigin = parseHttpsOrigin(
    requireEnvironmentVariable("IKACLO_API_ORIGIN"),
    "IKACLO_API_ORIGIN",
  );
  await Bun.write(varsPath, generatedMarker + [
    `CATALOG_URL=${JSON.stringify(catalogUrl)}`,
    `CORS_ALLOWED_ORIGINS=${JSON.stringify("http://localhost:5173,http://127.0.0.1:5173")}`,
    `IKACLO_API_ORIGIN=${JSON.stringify(imageOrigin)}`,
    `ADMIN_ENVIRONMENT="local"`,
    `ADMIN_ALLOWED_ORIGINS=${JSON.stringify("http://localhost:5174,http://127.0.0.1:5174")}`,
    `ADMIN_API_TOKEN=${JSON.stringify(process.env.ADMIN_API_TOKEN?.trim() ?? "")}`,
  ].join("\n") + "\n");
  await chmod(varsPath, 0o600);
}

await mkdir(resolve(apiRoot, ".data"), { recursive: true });
await writeLocalVars();
await Bun.write(seedPath, createLocalSeedSql());
await runWrangler([
  "d1", "migrations", "apply", "DB", "--local",
  "--config", "wrangler.local.toml", "--persist-to", stateDirectory,
]);
await runWrangler([
  "d1", "execute", "DB", "--local", "--yes",
  "--config", "wrangler.local.toml", "--persist-to", stateDirectory,
  "--file", seedPath,
]);
